"""Transformer-type controller (spec §9; audit-2 §B5/B6/C4/C7/D3): the future joint composition is
generated by *relational reference* to the current materials, the realized current composition, the
goal and the committed composition events of the history.

Tokens (§9.1).  Queries are the M track tokens at the current analysis row (track 0 = goal),
each carrying its normalized material feature f_i(t) = unit.f_mat[t, i, :].  Keys/values are

  p = 0            the goal token,          value  xi_G(t) - xi^current
  p = 1 .. M-1     the material tokens,     value  nu_p  = xi^{probe,p}(t) - xi^current
  memory head      committed events of H,   value  dxi^{event}  (realized composition change)
                   + a small per-track long-term digest of committed events (audit C7: a short
                     recent list plus a small long-term summary, kept in history.mode_state)

with xi^{probe,p} = unit.probe(g), g[p] = probe_foreground_gain, all other tracks
probe_background_gain (a probe is analysis material, never an immediate gain command), and
xi^current the running ideal state of the autoregression.  The number of tokens therefore depends
on M *and* on the committed history; an empty recollection attends a single zero-valued token.

Attention (§9.2, eq. 35):

  A^h_{ip} = softmax_p( S^h_{ip} + B^h_{ip}(H) - M^h_{ip} )
  S^sim_{ip}      = -||f_i - f_p||^2 / (2 sigma_F^2)
  S^contrast_{ip} = +||f_i - f_p||^2 / (2 sigma_F^2)
  S^memory_{ip}   = -||f_i - k_p||^2 / (2 sigma_F^2) - (t - t_p) / tau_H      (k_p = phi-block
                    of the event's xi_end, t_p its end time)
  B(H)            = bias_scale * tanh(corr(M_H)) + bias_scale * tanh(gain * centered(A_EMA))
                    both read from the COMMITTED history only (history.corr(),
                    history.mode_state["transformer"]["attention_ema"])
  M               = 0 allowed / +inf forbidden; the similarity and contrast heads mask
                    self-reference, every query keeps at least one key.

  O_h = (1/M) sum_i sum_p A^h_{ip} nu_p                                        (eq. 36)

Conditional future of the whole composition (§9.3, eq. 37/38), run on the MODEL step:

  mu_{j+1} = xi_j + (dt/dt_ref) [ o_j (a_s O_sim - a_c O_contrast + a_m O_memory)
                                  + a_G (1 - o_j) (xi_G - xi_j) ]
  Sigma_j  = noise_scale^2 sum_h O_h O_h^T + cov_diag_floor I
  xi_{j+1} = mu_{j+1} + sqrt(dt/dt_ref) o_j L eps,  eps AR(1) with rho = exp(-dt_model/tau_noise),
             followed by the bounded radial tanh excursion (once per model step); the sampled xi
             stays the context of the next step; GOAL_HOLD rows are pinned to xi_G and future
             hypotheses never enter history.events (the engine writes committed events itself).

Audit-2 changes (B5/C4/D3):

* `prepare_reference(unit, history, rows, xi_current, n)` builds the reference for the next
  lookahead window only, starting from the REALIZED current composition `xi_current` (not from the
  unit-start silence/goal probe), with the memory head attending the committed events available at
  that moment and B(H) from the committed history.  The engine freezes one of the returned
  proposals; it never moves while the gain trajectory is improved against it.
* the within-unit feedback bias that adapted the reference toward realized candidates is removed
  (`update()` is not called any more and is not implemented here).
* `observe_committed(...)` is the only learning step: the attention actually used for the committed
  block updates the attention EMA / reference order and the long-term memory digest with the
  history rate rho = 1 - exp(-dt / tau_H), persisted JSON-able in history.mode_state["transformer"].
* three time scales are separated (B6/D3.4): the analysis hop, the model step
  (`analysis.model_step_seconds`, stride = round(model_step / hop) >= 1) and the AR correlation
  time `tau_noise_seconds` (rho = exp(-model_step / tau_noise)).  Changing the analysis hop alone
  does not change the expressed dynamics (trace field `time_scale`).

Fragment-vocabulary revision (docs/FRAG_CONTRACT.md, 2026-09-16), active exactly when the analyzer
carries a fragment bank (`an.frag_f`) and the engine has published the source PCM on the mode
(`self.sources`).  Everything below replaces the *token side* only; the attention of eq. (35), the
autoregression of eq. (37)/(38) and all learning hooks keep their form.

* TOKENS ARE FRAGMENTS.  Per source i >= 1 the vocabulary holds K = 6
  (`transformer.fragment_tokens_per_source`) fragment positions of that source:
    - the fragment currently played by i (always included, and the only one masked as
      self-reference for query i),
    - ceil((K-1)/2) positions whose clip-averaged fragment features `an.frag_f[i]` are CLOSEST to
      the features that source i is actually playing now (`unit.f_mat[row0, i]`) — the relevance a
      similarity head can use,
    - the remaining (K-1) positions whose clip-averaged band profile is FARTHEST from the band
      block of the current composition `xi_current[1:1+nb]` — the relevance a contrast head can
      use.  Silent fragments (`an.frag_E < an.silence_energy`) are pushed to the back of both
      lists.  Plus one goal token (p = 0), key = the goal track's own fragment features.
* TOKEN VALUES ARE EXACT COMPOSITION DIFFERENCES.  nu_p = <xi(foreground p)> - <xi(no change)>,
  both computed with `an.grams_at_positions` / `an.composition_from_grams` (i.e. exactly what
  `an.fragment_composition` computes, batched into a single Gram call) for the fragment at
  `probe_foreground_gain`, every other track at its CURRENT level and CURRENT position, averaged
  over `fragment_value_offsets` = 3 offsets spread over the fragment clip.  The goal token keeps
  its original value xi_G - xi_current.  The absolute key composition of a token is therefore
  xi_key_p = xi_current + nu_p, an exactly realizable mixture, and the similarity / contrast heads
  stay the "relative" heads of eq. (37) with those keys.
* CURRENT STATE.  Positions come from `stats["positions"]` of the last committed block, advanced by
  the elapsed frames (playback clocks run at 1:1 between commits); at unit start the continuous
  clock `(window start) mod L_i` is used.  Material levels are tracked exactly from the committed
  events' `end_gain`; the goal level follows the exposure schedule, which is constant over the
  windowed search.  The distance between the reconstructed current composition and the realized
  `xi_current` is recorded per window (`current_composition_reconstruction_dist2`).
* BOUND.  The radial tanh excursion is kept, but anchored and sized in the fragment vocabulary:
  anchor (1-o) xi_G + o * xi_current, radius `excursion_radius_fragment` * o_j * max_p d_xi(nu_p, 0)
  over the fragment tokens * (1 + min(s, cap)) with s the model-step index inside the window — at
  openness o, after s+1 commit steps the ideal may be up to s+1 maximal one-step fragment moves away
  from the composition the realizer is actually at, and at o = 0 the ball collapses onto xi_G.  Its
  usage rate is recorded per unit.
* TIME.  In fragment mode the increment of eq. (37) is defined per MODEL step (dt_scale = 1,
  `fragment_step_seconds_reference` = the model step): one token value is what the realizer can do
  in one commit step, so the ideal moves per step by a realizable amount.  The mean per-step
  displacement of the ideal is recorded in d_xi units.
* STATISTICS (per commit / per unit): attention entropy per head (nats and normalized), the
  recurrence fraction (model steps whose top memory reference is an event whose `src_position` is
  within `recurrence_tolerance_seconds` = 2 s of the position played in the committed block), the
  bound usage rate and the mean per-step displacement of the ideal.

When the fragment bank is absent every one of these branches is skipped and the mode behaves
exactly as before (baseline configs).

Held realizable ideals (docs/HOLD_CONTRACT.md, 2026-09-16, user-requested), active exactly when the
engine publishes `unit.realizer_state` (`hires.reference_hold_seconds` > `commit_seconds`).  The
diagnosis was that averaging ALL token values into one displacement produced a free ideal step of
0.10 d_xi against the material's own 0.46 per commit: the attention never became audible.  New law —
**the heads SELECT**:

* `prepare_reference` is called once per 2 s hold and returns ONE plan, not a free trajectory.
* Per model step k of the hold (= one commit frame) the token bank is rebuilt from the CURRENT PLAN
  state — the positions the plan is playing after its earlier jumps, the levels it has reached — and
  the three heads of eq. (35) are evaluated with those query features.  After a selected jump the
  query features change: that is the autoregression, now over realizable states.
* The fragment tokens of the material tracks and the `src_position` of every committed memory event
  are the same kind of object: a realizable move (track, source position).  They are merged into one
  selection distribution, the heads entering with their own alpha AND SIGN exactly as in eq. (37)
  (the contrast head subtracts):  score(move) = sum_h sign_h alpha_h A^h(move), standardised, softmax
  at `hold_temperature`.
* The openness gates the move: a step moves with probability clip(o * `hold_move_rate`), so o = 0
  stays and GOAL_HOLD never moves.  `hold_candidates` tokens are drawn without replacement, each is
  turned into a plan step and its EXACT rows are evaluated with `realizer_state["plan_rows"]`; the
  step whose exact displacement is best aligned (d_xi metric) with the head-combined value
  sum_h sign_h alpha_h O_h of eq. (36) is taken.
* A token becomes a plan step: the selected track JUMPS to that fragment (when `frame >=
  next_jump_frame[track]` and no jump of that track earlier in the same plan within
  `min_clip_frames`; otherwise the level part alone) and is brought toward `probe_foreground_gain`,
  while every other material is brought toward the level the similarity / contrast structure gives it
  (`probe_background_gain` for the most contrasted, foreground for the closest companion).  All level
  moves are scaled by o * `hold_move_scale` (the recession additionally by `hold_background_scale`).
  A memory selection re-proposes a committed fragment, so recurrence becomes an actual RETURN.
* The published `xi_hat[rows]` are the EXACT `plan_rows` of the resulting plan and `meta["plan"]`
  carries the step list, so the engine can offer the jumps and the end levels as hints (R2).  The
  radial bound `_bound` and the free AR(1) path `_ar_path` are therefore not used in hold mode —
  every published state is already an exact realizable mixture.
* `observe_committed` is called once per COMMIT with the same held reference: the attention EMA, the
  memory-use record and every per-reference statistic are folded once per HOLD (at
  `stats["reference_is_new"]`) with rho = 1 - exp(-hold / tau_H); the memory digest and the played
  positions keep following the committed events at every commit.
* Statistics: attention entropy per head, recurrence (moves that return to a committed fragment),
  selected-token share per head and per track, jump / level-only / stay fractions, the requested
  move, and the internal iterations (tokens scored, realizable moves scored, candidate plan steps
  and `plan_rows` calls) kept apart from musical time.

Outside hold mode (`unit.realizer_state` missing / None) none of this runs: the branch is taken
before any RNG draw and the legacy code path is bit-identical (R5).

Realization (§9.4, eq. 39): E_T = <d_xi^2(xi_t(gamma), xi_hat_t)> over the non-hold rows (the
window restriction of the same quantity is the default `window_error`).

Not a trained language model: a relational controller over acoustic-composition space
(structure contract T).  Attention weights are never written into gains.
"""
