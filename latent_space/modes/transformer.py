    # ================================================================== hints
    def hints(self, unit: UnitContext, history) -> List[tuple]:
        out: List[tuple] = []
        seen = set()

        def add(a: int, b: int, rel: str) -> None:
            key = (min(a, b), max(a, b), rel)
            if a != b and key not in seen:
                seen.add(key)
                out.append((int(a), int(b), rel))

        if self.M < 3:
            return out
        for h, rel, n in (("similarity", "sync", 2), ("contrast", "counter", 1)):
            if h not in self.att0:
                continue
            # by_track is (M, M) in both vocabularies (fragment tokens aggregated by their source)
            sub = np.array(self.att0[h]["by_track"][1:, 1:], dtype=np.float64)
            if sub.size == 0:
                continue
            np.fill_diagonal(sub, -np.inf)
            taken = 0
            for flat in np.argsort(-sub, axis=None):
                a, b = np.unravel_index(int(flat), sub.shape)
                before = len(seen)
                add(int(a) + 1, int(b) + 1, rel)
                taken += int(len(seen) > before)
                if taken >= n:
                    break
        return out

