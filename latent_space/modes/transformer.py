    def end_unit(self, unit: UnitContext, history, chosen: Realization, alternatives) -> None:
        st = dict(history.mode_state.get("transformer") or {})
        if self._unit_commits == 0:
            # no commit step ran (degenerate unit): fall back to the unit reference's attention
            meta = dict(chosen.target.meta or {})
            by = meta.get("attention_by_track", {})
            ema = dict(st.get("attention_ema") or {})
            for h in self.heads:
                cur = np.asarray(by.get(h, np.zeros((self.M, self.M))), dtype=np.float64)
                if cur.shape != (self.M, self.M):
                    cur = np.zeros((self.M, self.M))
                prev = np.asarray(ema.get(h, self.A_ema[h]), dtype=np.float64)
                if prev.shape != (self.M, self.M):
                    prev = np.zeros((self.M, self.M))
                self.A_ema[h] = (1.0 - self.rho) * prev + self.rho * cur
                ema[h] = self.A_ema[h].tolist()
            st["attention_ema"] = ema
            self._record_memory_use(meta)
        mass = np.asarray(self.A_ema[self._ref_head()], dtype=np.float64).sum(axis=0)
        order = [int(i) for i in np.argsort(-mass)]
