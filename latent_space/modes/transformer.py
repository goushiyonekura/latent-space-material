    # ================================================================== signature / trace
    def signature(self) -> np.ndarray:
        parts = [np.asarray(self.A_ema[h], dtype=np.float64).ravel() for h in self.heads]
        parts.append(np.array([float(self.n_events)]))
        parts.append(np.asarray(self.mu_det_mean, dtype=np.float64))
        return np.concatenate(parts)

